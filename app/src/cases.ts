// ─── Long-form stories ───────────────────────────────────────────────────────

export type CaseMetric = { v: string; l: string };
export type CaseBlock = { t: string; d: string };
export type CaseHighlight = { t: string; d: string };

export type CaseShot = { src: string; cap: string };

/** platform architecture, rendered as a layered diagram */
export type CaseStack = { layer: string; note: string; items: string[] };
/** credit for a partner who delivered part of the work */
export type CasePartner = { note: string; name: string; logo: string; url: string };
/** order lifecycle chips */
export type CaseFlow = { steps: string[]; note: string };
/** delivery timeline rows */
export type CasePhase = { when: string; t: string; d: string };
/** promo film block. `embed` is a player URL (YouTube/VK/Rutube/Kinescope);
 *  until one is supplied the block renders its poster and caption only. */
export type CaseFilm = { title: string; note: string; embed?: string; poster?: string };
/** additional sales channels, shown as a logo strip */
export type CaseChannels = { title: string; note: string; items: { name: string; logo: string }[] };
/** earned media coverage */
export type CasePress = { outlet: string; title: string; date: string; url: string };

export type CaseStory = {
  slug: string;
  category: string;
  title: string;
  lead: string;
  cover: string;
  /** project timeframe, shown next to the category chip */
  period?: string;
  /** short label row under the hero */
  tags: string[];
  /** headline stat strip in the hero */
  facts: CaseMetric[];
  task: string;
  /** what the agency assembled — the full-cycle workstreams */
  build: CaseBlock[];
  /** big result grid */
  results: CaseMetric[];
  /** optional photo/screenshot gallery */
  gallery?: CaseShot[];
  /** optional platform architecture diagram */
  stack?: CaseStack[];
  /** optional partner credit shown under the architecture diagram */
  stackPartner?: CasePartner;
  /** optional order lifecycle strip */
  flow?: CaseFlow;
  /** optional delivery timeline */
  phases?: CasePhase[];
  /** optional promo film */
  film?: CaseFilm;
  /** optional marketplace channel strip */
  channels?: CaseChannels;
  /** optional press coverage list */
  press?: CasePress[];
  /** qualitative wins */
  highlights: CaseHighlight[];
  /** pull-quote */
  quote: { text: string; author: string };
  /** closing note — e.g. what happened to the project afterwards */
  epilogue?: CaseBlock;
  /** team member names (matched against data.ts `team`) */
  team: string[];
  /** per-project role override, keyed by member name */
  roles?: Record<string, string>;
};

